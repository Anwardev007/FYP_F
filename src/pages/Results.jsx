import React, { useState, useEffect } from "react";
import axios from "axios";
import { useNavigate } from "react-router-dom";
import pdfMake from "../pdfmakeLoader";
import Layout from "../components/Layout";


function Results() {
  const [comparisons, setComparisons] = useState([]);
  const navigate = useNavigate();

  useEffect(() => {
    const fetchResults = async () => {
      try {
        const response = await axios.get("http://localhost:5000/results", {
          headers: {
            Authorization: `Bearer ${localStorage.getItem("token")}`,
          },
        });
        console.log("Response", response.data.results)
        setComparisons(response.data.results || []);
        console.log("comparison", comparisons)
      } catch (error) {
        console.error("❌ Error fetching results:", error);
      }
    };
    fetchResults();
  }, []);

  const goToToolkit = () => navigate("/");

  // 🧾 Generate PDF document definition
  const generatePDF = () => {
    const tableBody = [
      [
        { text: "#", bold: true },
        { text: "File A", bold: true },
        { text: "File B", bold: true },
        { text: "Similarity %", bold: true },
        { text: "Plagiarized", bold: true },
      ],
      ...comparisons.map((comp, index) => [
        index + 1,
        comp.file1,
        comp.file2,
        `${comp.similarity}%`,
        comp.plagiarized ? "✅ Yes" : "❌ No",
      ]),
    ];

    const docDefinition = {
      content: [
        { text: "Plagiarism Detection Report", style: "header" },
        {
          text: `Generated on: ${new Date().toLocaleString()}`,
          style: "subheader",
        },
        {
          table: {
            headerRows: 1,
            widths: ["auto", "*", "*", "auto", "auto"],
            body: tableBody,
          },
          layout: {
            fillColor: (rowIndex) =>
              rowIndex === 0
                ? "#4472C4"
                : rowIndex % 2 === 0
                  ? "#F3F3F3"
                  : null,
          },
          style: "table",
        },
        {
          text: "\nSummary:",
          style: "subheader",
        },
        {
          text: `Total Comparisons: ${comparisons.length}\nAverage Similarity: ${comparisons.reduce((a, c) => a + c.similarity, 0) /
            comparisons.length || 0
            }%`,
          margin: [0, 0, 0, 20],
        },
        {
          text: "Generated by FacewellAI-Suite — AI Toolkit",
          style: "footer",
        },
      ],
      styles: {
        header: {
          fontSize: 22,
          bold: true,
          alignment: "center",
          margin: [0, 0, 0, 10],
        },
        subheader: {
          fontSize: 12,
          italics: true,
          margin: [0, 5, 0, 10],
        },
        table: {
          margin: [0, 10, 0, 10],
          fontSize: 11,
        },
        footer: {
          italics: true,
          fontSize: 10,
          alignment: "center",
          color: "#555",
        },
      },
      defaultStyle: {
        font: "Roboto"
      },
    };

    return docDefinition;
  };

  // ⬇️ Download PDF
  const handleDownload = () => {
    if (comparisons.length === 0) return alert("No results to download.");
    const pdfDoc = pdfMake.createPdf(generatePDF());
    pdfDoc.download(`Plagiarism_Report_${Date.now()}.pdf`);
  };

  // 📤 Share PDF on WhatsApp
  const handleShare = async () => {
    if (comparisons.length === 0) return alert("No results to share.");

    const pdfDoc = pdfMake.createPdf(generatePDF());

    // Generate and download the PDF first
    pdfDoc.download("Plagiarism_Report.pdf");

    // Wait a moment to ensure file saves
    setTimeout(() => {
      const message = encodeURIComponent(
        "📄 Plagiarism Detection Report generated by AI Toolkit!\n\nThe report has been downloaded to your device. Please attach it below and send it."
      );

      const whatsappWebURL = `https://web.whatsapp.com/send?text=${message}`;
      window.open(whatsappWebURL, "_blank");
    }, 1000); // wait 1 second before opening WhatsApp
  };

  return (
    <Layout>
      <div
        className="min-h-screen flex items-center justify-center bg-gradient-to-br from-blue-900 via-purple-900 to-black px-6 py-12"
        style={{ backgroundAttachment: "fixed" }}
      >
        <div className="bg-white/10 backdrop-blur-2xl border border-white/20 rounded-3xl shadow-2xl p-8 max-w-5xl w-full text-white">
          <h2 className="text-4xl font-extrabold text-center mb-8">
            📊 Plagiarism Detection Results
          </h2>

          {comparisons.length === 0 ? (
            <p className="text-center text-white/80">No results to display.</p>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full border-collapse rounded-lg overflow-hidden">
                <thead>
                  <tr className="bg-white/20 text-white text-lg">
                    <th className="p-3 border border-white/20">File A</th>
                    <th className="p-3 border border-white/20">File B</th>
                    <th className="p-3 border border-white/20">Similarity %</th>
                    <th className="p-3 border border-white/20">Plagiarized</th>
                  </tr>
                </thead>
                <tbody>
                  {comparisons.map((comp, index) => (
                    <tr
                      key={index}
                      className={`text-center text-white/90 ${comp.plagiarized
                        ? "bg-red-500/20 hover:bg-red-500/30"
                        : "hover:bg-green-500/20"
                        } transition`}
                    >
                      <td className="p-3 border border-white/20">{comp.file1}</td>
                      <td className="p-3 border border-white/20">{comp.file2}</td>
                      <td className="p-3 border border-white/20 font-semibold">
                        {comp.similarity}%
                      </td>
                      <td className="p-3 border border-white/20 font-bold">
                        {comp.plagiarized ? "✅ Yes" : "❌ No"}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          <div className="flex flex-wrap justify-center gap-4 mt-10">
            <button
              onClick={handleDownload}
              className="px-6 py-3 rounded-lg bg-gradient-to-r from-green-500 to-teal-500 font-semibold hover:scale-105 shadow-lg transition-all duration-300"
            >
              ⬇️ Download PDF
            </button>
            <button
              onClick={handleShare}
              className="px-6 py-3 rounded-lg bg-gradient-to-r from-yellow-400 to-orange-500 font-semibold hover:scale-105 shadow-lg transition-all duration-300"
            >
              📤 Share via WhatsApp
            </button>
            <button
              onClick={goToToolkit}
              className="px-6 py-3 rounded-lg bg-gradient-to-r from-blue-500 to-purple-600 font-semibold hover:scale-105 shadow-lg transition-all duration-300"
            >
              🧰 Go to Toolkit
            </button>
          </div>
        </div>
      </div>
    </Layout>
  );
}

export default Results;
